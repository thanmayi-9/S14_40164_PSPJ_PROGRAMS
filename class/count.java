public class count{
    
    public static void main(String[] args){
        int count = 10;
        System.out.println("Post increment = "+(count++));

        System.out.println("Pre increment = "+(++count));
        
        System.out.println("Post decrement = "+(count--));

        System.out.println("Pre decrement = "+(--count));
    }
}

