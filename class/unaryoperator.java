public class unaryoperator{
public static void main(String[] args){
   int a = 10;
   int b = 10;
  
   System.out.println("post increment = "+ a++ );
   System.out.println("pre increment = " + ++a);

   System.out.println("post increment = "+ b++ );
   System.out.println("pre increment = " + ++b);

}
}